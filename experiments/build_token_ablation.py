"""
build_token_ablation.py
=======================
Concatenates margin_core.py + token_ablation_driver.py into one self-contained
Kaggle kernel script, with CONFIG baked in.

Same shape as build_kernel.py, including its two hard-won guards: pprint rather
than json.dumps for the CONFIG block, because json renders None/True/False as
null/true/false, which parse as legal Python names and then fail at runtime on
the GPU; and a literal_eval round-trip at build time so a stray bare name costs
a build, not a GPU session.

Usage:
  python build_token_ablation.py --mode smoke   # 1 model, 20 prompts
  python build_token_ablation.py --mode open    # 4 ungated models, 300 prompts
  python build_token_ablation.py --mode llama   # the 2 gated models
"""

import argparse
import ast
import json
import os
import pprint
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DATASET_SLUG = "slm-quant-attack-prompts"

MODES = {
    "smoke": {
        "models": ["qwen2.5-1.5b"],
        "limit_prompts": 20,
        "jailbreak_only": True,
    },
    # Llama-3.2 is gated and needs a Kaggle Secret attached to the specific
    # notebook through the web UI. Split so the ungated run never blocks on it.
    "open": {
        "models": ["qwen2.5-1.5b", "qwen2.5-3b", "falcon3-1b", "falcon3-3b"],
        "limit_prompts": None,
        "jailbreak_only": True,
    },
    "llama": {
        "models": ["llama3.2-1b", "llama3.2-3b"],
        "limit_prompts": None,
        "jailbreak_only": True,
    },
}


def build(mode, out_dir):
    core = open(os.path.join(HERE, "margin_core.py"), encoding="utf-8").read()
    driver = open(os.path.join(HERE, "token_ablation_driver.py"),
                  encoding="utf-8").read()

    cfg = dict(MODES[mode])
    cfg["dataset_dir"] = f"/kaggle/input/{DATASET_SLUG}"
    cfg["out_dir"] = "/kaggle/working"

    new_block = "CONFIG = " + pprint.pformat(cfg, indent=4, width=78,
                                             sort_dicts=False)
    driver, n = re.subn(r"CONFIG = \{.*?\n\}", new_block, driver, count=1,
                        flags=re.DOTALL)
    if n != 1:
        raise RuntimeError("Could not substitute the CONFIG block in the driver.")

    # Drop the driver's module docstring; it would otherwise sit mid-file.
    driver = re.sub(r'^""".*?"""\n', "", driver, count=1, flags=re.DOTALL)

    header = (
        "# ==========================================================\n"
        f"# GENERATED by build_token_ablation.py --mode {mode} -- DO NOT EDIT HERE.\n"
        "# Edit margin_core.py / token_ablation_driver.py and rebuild.\n"
        "# ==========================================================\n\n"
    )
    kernel = (header + core + "\n\n# " + "=" * 58 + "\n# DRIVER\n# "
              + "=" * 58 + "\n\n" + driver)

    tree = ast.parse(kernel)
    baked = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
            isinstance(t, ast.Name) and t.id == "CONFIG" for t in node.targets
        ):
            baked = ast.literal_eval(node.value)
    if baked is None:
        raise RuntimeError("No CONFIG assignment found in the generated kernel.")
    if baked != cfg:
        raise RuntimeError(f"CONFIG did not round-trip.\n wanted: {cfg}\n got: {baked}")

    # The whole point of the kernel is that the two refusal sets differ in their
    # first token. If a future edit makes them identical the run measures
    # nothing, so check it here rather than after a GPU session.
    names = {n.targets[0].id for n in tree.body
             if isinstance(n, ast.Assign) and isinstance(n.targets[0], ast.Name)}
    for required in ("REFUSAL_CONTINUATIONS", "ALT_REFUSAL_CONTINUATIONS",
                     "ALT_COMPLIANCE_CONTINUATIONS"):
        if required not in names:
            raise RuntimeError(f"{required} missing from the generated kernel.")
    sets = {}
    for node in tree.body:
        if (isinstance(node, ast.Assign)
                and isinstance(node.targets[0], ast.Name)
                and node.targets[0].id in ("REFUSAL_CONTINUATIONS",
                                           "ALT_REFUSAL_CONTINUATIONS")):
            sets[node.targets[0].id] = ast.literal_eval(node.value)
    if sets["REFUSAL_CONTINUATIONS"] == sets["ALT_REFUSAL_CONTINUATIONS"]:
        raise RuntimeError("The two refusal sets are identical; nothing to ablate.")

    os.makedirs(out_dir, exist_ok=True)
    path = os.path.join(out_dir, "token-ablation.py")
    with open(path, "w", encoding="utf-8") as f:
        f.write(kernel)

    meta = {
        "id": f"razanml/slm-token-ablation-{mode}",
        "title": f"SLM token ablation {mode}",
        "code_file": "token-ablation.py",
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [f"razanml/{DATASET_SLUG}"],
        "competition_sources": [],
        "kernel_sources": [],
    }
    # Kaggle creates the kernel at the slug derived from the TITLE, not at the
    # metadata id. A mismatch produces a kernel at an address every later
    # `kernels status` call fails against, with an error that reads like auth.
    slug = meta["title"].lower().replace(" ", "-")
    if meta["id"].split("/")[1] != slug:
        raise RuntimeError(
            f"title slug {slug!r} does not match metadata id {meta['id']!r}; "
            "Kaggle would create the kernel at the title's slug")

    with open(os.path.join(out_dir, "kernel-metadata.json"), "w",
              encoding="utf-8") as f:
        json.dump(meta, f, indent=2)

    n_prompts = cfg["limit_prompts"] or 300
    print(f"Built {path}")
    print(f"  mode={mode}  models={len(cfg['models'])}  prompts={n_prompts}")
    print(f"  {2 * n_prompts * len(cfg['models']):,} margin measurements "
          "(two continuation sets per prompt, no perturbation)")
    print(f"  kernel id: {meta['id']}")
    # The default Kaggle GPU is a P100 (sm_60), below this torch build's sm_70
    # floor; without the flag every model dies on the first matmul.
    print(f"  push with: kaggle kernels push -p {out_dir} "
          "--accelerator NvidiaTeslaT4")
    return path


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--mode", choices=list(MODES), default="smoke")
    ap.add_argument("--out", default=None)
    args = ap.parse_args()
    build(args.mode, args.out or os.path.join(HERE, "_build",
                                              f"token-{args.mode}"))
