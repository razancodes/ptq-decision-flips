"""
build_mechanism.py
==================
Build the alpha_equiv + delta_m kernel (tasks 1.3 and 1.4) by concatenating
margin_core.py with mechanism_driver.py, the same way build_kernel.py composes
the Study B kernel -- a Kaggle script kernel is a single file, and m_first must
be measured by exactly the code that measured it in Study B or delta_m is not a
difference of like quantities.

Usage:  python build_mechanism.py
        cd experiments/_build/mechanism && kaggle kernels push -p . \
            --accelerator NvidiaTeslaT4
"""

import argparse
import ast
import json
import os
import pprint
import re

HERE = os.path.dirname(os.path.abspath(__file__))
KERNEL_ID = "razanml/slm-mechanism"
CODE_FILE = "mechanism.py"
DATASET_SLUG = "slm-quant-attack-prompts"


def build(limit_prompts=None, model_keys=None, name=None):
    """name defaults to the original Falcon3 kernel, so existing use is unchanged.

    A different name gives a different kernel id AND a different _build
    directory, which matters because _build/mechanism holds the kernel that
    actually produced the published Falcon3 alpha_equiv and must not be
    overwritten by a Qwen rebuild.
    """
    model_keys = model_keys or ["falcon3-1b", "falcon3-3b"]
    suffix = f"-{name}" if name else ""
    core = open(os.path.join(HERE, "margin_core.py"), encoding="utf-8").read()
    driver = open(os.path.join(HERE, "mechanism_driver.py"), encoding="utf-8").read()

    cfg = {
        "model_keys": model_keys,
        "methods": ["awq", "gptq", "gguf"],
        "limit_prompts": limit_prompts,
        "alpha_equiv_sane_range": [0.002, 0.6],
        "unbiased_tol_steps": 0.25,
        "dataset_dir": f"/kaggle/input/{DATASET_SLUG}",
        "out_dir": "/kaggle/working",
    }

    driver, n = re.subn(
        r"CONFIG = \{.*?\n\}",
        "CONFIG = " + pprint.pformat(cfg, indent=4, width=78, sort_dicts=False),
        driver, count=1, flags=re.DOTALL,
    )
    if n != 1:
        raise RuntimeError("CONFIG substitution failed")

    # gguf is pure python; install it if the image lacks it.
    install = (
        'import subprocess, sys\n'
        'try:\n'
        '    import gguf  # noqa: F401\n'
        'except ImportError:\n'
        '    print("installing gguf", flush=True)\n'
        '    subprocess.check_call([sys.executable, "-m", "pip", "install", "-q",\n'
        '                           "gguf"])\n'
        '\n'
    )

    driver = re.sub(r'^""".*?"""\n', "", driver, count=1, flags=re.DOTALL)
    header = (
        "# ==========================================================\n"
        "# GENERATED by build_mechanism.py -- DO NOT EDIT HERE.\n"
        "# Edit margin_core.py / mechanism_driver.py and rebuild.\n"
        "# ==========================================================\n\n"
    )
    kernel = (header + install + core + "\n\n# " + "=" * 58 +
              "\n# DRIVER\n# " + "=" * 58 + "\n\n" + driver)

    tree = ast.parse(kernel)
    baked = None
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                isinstance(t, ast.Name) and t.id == "CONFIG" for t in node.targets):
            baked = ast.literal_eval(node.value)
    if baked != cfg:
        raise RuntimeError(f"CONFIG did not round-trip:\n wanted {cfg}\n got {baked}")
    for needed in ("def margin(", "REFUSAL_CONTINUATIONS", "def score_continuations("):
        if needed not in kernel:
            raise RuntimeError(f"margin_core symbol missing from kernel: {needed}")

    # Every key the driver reads out of CONFIG must exist in the baked CONFIG.
    # Version 2 of this kernel lost all six quantized cells to a single missing
    # key (`alpha_equiv_sane_range`) that only surfaced at runtime, per model,
    # after the fp16 work had already been done. A build-time check costs
    # nothing and turns that into a failed build.
    read_keys = set(re.findall(r'cfg\["([a-z_0-9]+)"\]', kernel))
    read_keys |= set(re.findall(r'CONFIG\["([a-z_0-9]+)"\]', kernel))
    missing = sorted(read_keys - set(cfg))
    if missing:
        raise RuntimeError(
            f"the driver reads CONFIG keys that the build does not set: "
            f"{missing}. Add them to cfg in this file.")
    unused = sorted(set(cfg) - read_keys)
    if unused:
        print(f"  note: CONFIG keys never read by the driver: {unused}")

    meta = {
        "id": KERNEL_ID + suffix,
        "title": "SLM mechanism" + (f" {name}" if name else ""),
        "code_file": CODE_FILE,
        "language": "python",
        "kernel_type": "script",
        "is_private": True,
        "enable_gpu": True,
        "enable_internet": True,
        "dataset_sources": [f"razanml/{DATASET_SLUG}"],
        "competition_sources": [],
        "kernel_sources": [],
    }

    out = os.path.join(HERE, "_build", "mechanism" + suffix)
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, CODE_FILE), "w", encoding="utf-8") as fh:
        fh.write(kernel)
    with open(os.path.join(out, "kernel-metadata.json"), "w", encoding="utf-8") as fh:
        json.dump(meta, fh, indent=2)

    written = json.load(open(os.path.join(out, "kernel-metadata.json"), encoding="utf-8"))
    if written["id"] != KERNEL_ID + suffix:
        raise RuntimeError(f"metadata id mismatch: {written['id']}")

    n_margin = len(cfg["model_keys"]) * (len(cfg["methods"]) + 1) * \
        (limit_prompts or 400)
    print(f"Built {out}")
    print(f"  kernel id : {written['id']}")
    print(f"  models    : {cfg['model_keys']}")
    print(f"  methods   : {cfg['methods']} (+ fp16 reference)")
    print(f"  margins   : {n_margin:,} m_first measurements")
    print(f"  push with : cd {out} && kaggle kernels push -p . "
          f"--accelerator NvidiaTeslaT4")
    return out


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--limit-prompts", type=int, default=None,
                    help="smoke mode: only the first N prompts")
    ap.add_argument("--models", nargs="+", default=None,
                    help="model_registry keys; default is the Falcon3 pair")
    ap.add_argument("--name", default=None,
                    help="suffix for the kernel id and _build dir, e.g. qwen")
    args = ap.parse_args()
    build(args.limit_prompts, args.models, args.name)
